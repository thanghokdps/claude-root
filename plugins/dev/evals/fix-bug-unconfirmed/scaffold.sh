#!/usr/bin/env bash
# Seeds a small checkout service; the prompt brings only a one-line production log.
set -euo pipefail
here="$(dirname "${BASH_SOURCE[0]}")"
git init -q -b main
git config user.email eval@example.com && git config user.name eval
cp -R "$here/repo/." .
git add -A && git commit -qm "init: checkout service"
